"""Offline verification for the vendored Colab CLI patches.

Stdlib only, no network, no GPU, no credentials. Run from the repo root:
    python3 scripts/verify_patch.py

Checks:
1. Both patch files exist under patches/google-colab-cli-0.7.5/ and are
   well-formed unified diffs against pristine google-colab-cli 0.7.5
   (--- a/colab_cli/... headers, and the expected added lines).
2. h3_controller.py contains the fail-closed patch-presence checks
   (cli_post_body_patch_present / cli_drivemount_timeout_patch_present).
3. If a colab_cli install is importable in this Python, report (only) whether
   that copy is patched — informational, never a failure here, because CI
   has no venv.

The patches themselves were generated by diffing the pristine 0.7.5 wheel
against the patched venv copy and verified with `git apply --check` plus a
byte-identical round-trip; see patches/google-colab-cli-0.7.5/README.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATCH_DIR = ROOT / "patches" / "google-colab-cli-0.7.5"

EXPECTED = {
    "proxy_post_body.patch": [
        "--- a/colab_cli/client.py",
        'kwargs["data"] = b"{}"',
        'if method == "POST" and "data" not in kwargs and "json" not in kwargs:',
    ],
    "drivemount_timeout.patch": [
        "--- a/colab_cli/commands/automation.py",
        "timeout_ms=600000",
        "INTERACTIVE_AUTOMATION_TIMEOUT_SEC = 660",
    ],
}


def main() -> int:
    errors = []
    for name, markers in EXPECTED.items():
        p = PATCH_DIR / name
        if not p.is_file():
            errors.append(f"MISSING: patches/google-colab-cli-0.7.5/{name}")
            continue
        text = p.read_text()
        for m in markers:
            if m not in text:
                errors.append(f"{name}: missing expected diff content: {m!r}")
        if not text.startswith("--- a/"):
            errors.append(f"{name}: not a unified diff (no '--- a/' header)")
    controller = (ROOT / "h3_controller.py").read_text()
    for fn in ("cli_post_body_patch_present", "cli_drivemount_timeout_patch_present"):
        if f"def {fn}" not in controller:
            errors.append(f"h3_controller.py: missing fail-closed check {fn}")
    # Informational only: is the colab_cli visible to this interpreter patched?
    try:
        import colab_cli  # noqa: F401
        import site

        for base in site.getsitepackages():
            cand = Path(base) / "colab_cli" / "client.py"
            if cand.exists():
                patched = 'kwargs["data"] = b"{}"' in cand.read_text(errors="ignore")
                print(f"INFO: installed colab_cli at {cand}: post-body patch present={patched}")
                break
    except Exception:
        print("INFO: no importable colab_cli in this interpreter (expected in CI).")
    if errors:
        print("PATCH VERIFY FAILED:")
        for e in errors:
            print("  " + e)
        return 1
    print("PATCH VERIFY OK: both 0.7.5 diffs well-formed, controller checks present.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
